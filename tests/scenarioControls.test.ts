import assert from 'node:assert/strict';
import {createScenarioControls, scenarioControlsReducer as reduce, scenarioFromControls} from '../src/utils/scenarioControls';
import type {StressScenario} from '../src/types/risk';
const scenario: StressScenario = {id:'test',name:'Market drop',description:'',category:'custom',drivers:{market:-20},tickerShocks:{NVDA:-0.1}};
const original = createScenarioControls(scenario);
assert.deepEqual(scenarioFromControls(original), scenario);
let state = reduce(original,{type:'factor',key:'technology',value:-30});
assert.deepEqual(scenarioFromControls(state).drivers,{market:-20,technology:-30});
assert.deepEqual(scenarioFromControls(state).tickerShocks,{NVDA:-0.1});
state=reduce(state,{type:'toggle-factor',key:'market',enabled:false});
assert.equal(Object.hasOwn(scenarioFromControls(state).drivers!,'market'),false,'omitted driver must not become an unchanged-market constraint');
state=reduce(state,{type:'toggle-factor',key:'treasury10y',enabled:true});
assert.equal(scenarioFromControls(state).drivers?.treasury10y,0,'explicit zero is a constraint');
state=reduce(state,{type:'ticker',ticker:'spy',value:0});
assert.equal(scenarioFromControls(state).tickerShocks.SPY,0,'explicit zero is retained');
state=reduce(state,{type:'reset-ticker',ticker:'NVDA'});
assert.equal(Object.hasOwn(scenarioFromControls(state).tickerShocks,'NVDA'),false);
assert.deepEqual(scenarioFromControls(reduce(state,{type:'reset'})),scenario);
assert.equal(reduce(state,{type:'factor',key:'market',value:-99}),state,'out-of-range input must not silently clamp');
assert.equal(reduce(state,{type:'ticker',ticker:'SPY',value:NaN}),state);
assert.deepEqual(scenarioFromControls(reduce(state,{type:'use-factors'})).tickerShocks,{});
assert.deepEqual(scenario,{id:'test',name:'Market drop',description:'',category:'custom',drivers:{market:-20},tickerShocks:{NVDA:-0.1}},'edits must not mutate submitted assumptions');
console.log('Scenario control tests passed');
